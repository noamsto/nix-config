#!/usr/bin/env bash
# PreToolUse hook: block a commit/tag message or PR/issue body that carries a
# coding-agent attribution footer ("Generated with Claude Code",
# "Co-Authored-By: Claude …", "noreply@anthropic.com"). Attribution is off in
# Claude Code's settings, but the model still writes the footer into
# `gh pr create --body` text unprompted, so a setting cannot stop it. This
# refuses the call and asks for the line to be dropped.
#
# Denies only when the call runs one of the commit/PR/issue commands below AND
# its text, or a message/body file it names, contains a marker. A missing or
# unreadable file is not a denial.

set -euo pipefail

input=$(cat)

tool_name=$(jq -r '.tool_name // empty' <<<"$input")
[[ $tool_name == "Bash" ]] || exit 0

command=$(jq -r '.tool_input.command // empty' <<<"$input")
[[ -n $command ]] || exit 0

# A backslash-newline continuation is a space to the shell; join it so a flag
# or a marker on the next line stays in the same command.
continuation=$'\\\n'
command=${command//"$continuation"/ }

markers=(
  'Generated with [Claude Code]'
  'Generated with Claude Code'
  'Generated by [Claude Code]'
  'Co-Authored-By: Claude'
  'noreply@anthropic.com'
)

has_marker() {
  local text=$1 marker
  shopt -s nocasematch
  for marker in "${markers[@]}"; do
    # Quoted, so the `[`/`]` in the marker are literal, not a glob class.
    if [[ $text == *"$marker"* ]]; then
      shopt -u nocasematch
      return 0
    fi
  done
  shopt -u nocasematch
  return 1
}

# git runs in the intercepted command's cwd, not the hook process's cwd.
cwd=$(jq -r '.cwd // empty' <<<"$input" || true)
cwd=${cwd:-$PWD}

git_word_re='(^|[[:space:];&|(/])git[[:space:]]'
gh_word_re='(^|[[:space:];&|(/])gh[[:space:]]'
commit_re='[[:space:]]commit([[:space:]]|$)'
commit_tree_re='[[:space:]]commit-tree([[:space:]]|$)'
tag_re='[[:space:]]tag([[:space:]]|$)'
# git tag -a/-m (and their long forms); -a/-m may sit in a short-flag cluster.
tag_message_re='(--(annotate|message)([[:space:]]|=)|[[:space:]]-[a-zA-Z]*[am][a-zA-Z]*([[:space:]]|$))'
pr_re='[[:space:]]pr[[:space:]]+(create|edit|comment|review)([[:space:]]|$)'
issue_re='[[:space:]]issue[[:space:]]+(create|edit|comment)([[:space:]]|$)'
api_re='[[:space:]]api([[:space:]]|$)'
api_body_re='([[:space:]]|=)body=|[[:space:]]--input([[:space:]]|=)'

qualifies=0
if [[ $command =~ $git_word_re ]]; then
  if [[ $command =~ $commit_re || $command =~ $commit_tree_re ]]; then
    qualifies=1
  elif [[ $command =~ $tag_re && $command =~ $tag_message_re ]]; then
    qualifies=1
  fi
fi
if [[ $qualifies -eq 0 && $command =~ $gh_word_re ]]; then
  if [[ $command =~ $pr_re || $command =~ $issue_re ]]; then
    qualifies=1
  elif [[ $command =~ $api_re && $command =~ $api_body_re ]]; then
    qualifies=1
  fi
fi
[[ $qualifies -eq 1 ]] || exit 0

denied=0
has_marker "$command" && denied=1

if [[ $denied -eq 0 ]]; then
  value_re='("[^"]+"|'\''[^'\'']+'\''|[^[:space:];&|]+)'
  files=()

  all_matches() {
    local rest=$1 re=$2
    matches=()
    while [[ $rest =~ $re ]]; do
      matches+=("${BASH_REMATCH[${#BASH_REMATCH[@]} - 1]}")
      rest=${rest#*"${BASH_REMATCH[0]}"}
    done
  }

  for re in \
    "[[:space:]]-F[[:space:]]+$value_re" \
    "[[:space:]]-F$value_re" \
    "[[:space:]]--file[[:space:]]+$value_re" \
    "[[:space:]]--file=$value_re" \
    "[[:space:]]--body-file[[:space:]]+$value_re" \
    "[[:space:]]--body-file=$value_re" \
    "[[:space:]]--input[[:space:]]+$value_re" \
    "[[:space:]]--input=$value_re"; do
    all_matches "$command" "$re"
    files+=("${matches[@]}")
  done

  for file in "${files[@]}"; do
    file=${file#[\"\']}
    file=${file%[\"\']}
    [[ $file == /* ]] || file=$cwd/$file
    [[ -f $file && -r $file ]] || continue
    content=$(cat "$file" 2>/dev/null) || continue
    if has_marker "$content"; then
      denied=1
      break
    fi
  done
fi

[[ $denied -eq 1 ]] || exit 0

jq -n '{
  hookSpecificOutput: {
    hookEventName: "PreToolUse",
    permissionDecision: "deny",
    permissionDecisionReason: "Remove the coding-agent attribution line or trailer (e.g. \"Generated with Claude Code\", \"Co-Authored-By: Claude …\") from the commit message, tag message or PR/issue body, then re-run the same command. This project does not use agent attribution."
  }
}'
